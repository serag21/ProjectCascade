#!/usr/bin/env python3
"""Generate the slice's effect textures as white-on-transparent PNGs (tinted in engine).

Usage: python3 design/fable/tools/make_textures.py     (needs Pillow + numpy)
Output: design/fable/assets/textures/*.png and a manifest. Original, procedural, no third-party source.
These must be uploaded to Roblox by the owner (Asset Manager > Images) before they can be used;
every effect has a no-texture fallback listed in 11_MEADOW_PRODUCTION_REFERENCE.md.
"""
import json, hashlib
from pathlib import Path
import numpy as np
from PIL import Image

OUT = Path(__file__).resolve().parents[1] / "assets" / "textures"
OUT.mkdir(parents=True, exist_ok=True)
manifest = {}

def save(name, alpha, use, w=None):
    a = np.clip(alpha, 0, 1)
    rgba = np.zeros(a.shape + (4,), dtype=np.uint8); rgba[..., :3] = 255; rgba[..., 3] = (a * 255 + 0.5).astype(np.uint8)
    Image.fromarray(rgba, "RGBA").save(OUT / name, optimize=True)
    data = (OUT / name).read_bytes()
    manifest[name] = {"size": [a.shape[1], a.shape[0]], "bytes": len(data), "sha256": hashlib.sha256(data).hexdigest(), "use": use}

def grid(w, h):
    u = (np.arange(w) + 0.5) / w; v = (np.arange(h) + 0.5) / h
    return np.meshgrid(u, v)

# Trail texture: U runs along the ribbon (tiles), V across it. Soft edges + a brighter core line.
U, V = grid(256, 64); d = np.abs(V - 0.5) * 2
soft = np.clip(1 - d, 0, 1) ** 0.8 * 0.55
core = np.exp(-(d / 0.22) ** 2) * 0.6
shimmer = 0.06 * np.sin(U * 2 * np.pi * 3) * (1 - d)
save("ribbon_trail.png", soft + core + shimmer, "Trail.Texture for the ribbon. TextureMode=Wrap, TextureLength=8. Tint with Trail.Color.")

# Cinch ring: hotter core, forward-leaning chevrons so TextureSpeed reads as tightening.
U, V = grid(256, 64); d = np.abs(V - 0.5) * 2
chev = (np.sin((U * 4 - d * 0.5) * 2 * np.pi) * 0.5 + 0.5) ** 2
save("cinch_ring.png", np.clip(1 - d, 0, 1) ** 0.6 * (0.55 + 0.45 * chev) + np.exp(-(d / 0.18) ** 2) * 0.5, "Beam.Texture for the 24 cinch-ring segments. TextureLength=6, TextureSpeed=1.5.")

# Snap preview: rounded dashes, 50% duty.
U, V = grid(128, 32); d = np.abs(V - 0.5) * 2
du = np.abs((U * 2) % 1 - 0.5) * 2          # 0 at dash centre, 1 at gap centre
dash = np.clip((0.55 - du) / 0.08, 0, 1) * np.clip((0.7 - d) / 0.15, 0, 1)
save("snap_dash.png", dash, "Beam.Texture for the snap-preview line (head to snap point). TextureLength=3, TextureSpeed=0.")

# Pop particle: soft four-point star.
U, V = grid(128, 128); x = (U - 0.5) * 2; y = (V - 0.5) * 2; r = np.hypot(x, y)
star = np.exp(-(np.abs(x) * np.abs(y)) * 60) * np.clip(1 - r, 0, 1) ** 1.5
save("pop_spark.png", star + np.exp(-(r / 0.22) ** 2) * 0.9, "ParticleEmitter.Texture for catch pops and golden sparkle. Tint per species.")

# Confetti: rounded rectangle.
U, V = grid(64, 64); x = np.abs(U - 0.5) * 2; y = np.abs(V - 0.5) * 2
save("confetti.png", np.clip((0.86 - np.maximum(x / 1.0, y / 0.62)) / 0.06, 0, 1), "ParticleEmitter.Texture for ROUNDUP / STAMPEDE confetti. RotSpeed 180-360.")

# Telegraph ring decal: crisp outer line, faint fill, used flat on the ground.
U, V = grid(512, 512); r = np.hypot((U - 0.5) * 2, (V - 0.5) * 2)
line = np.exp(-((r - 0.9) / 0.035) ** 2)
fill = np.clip((0.9 - r) / 0.02, 0, 1) * 0.16
save("telegraph_ring.png", line + fill, "Decal/SurfaceGui image on a flat pooled part: hop ring, bloom-burst radius, bank-ring ground mark, ghost ring in the first round.")

# Route chevron for the stampede telegraph.
U, V = grid(128, 128); x = (U - 0.5) * 2; y = (V - 0.5) * 2
arm = np.abs(np.abs(x) * 0.9 + y - 0.1)
save("route_chevron.png", np.clip((0.2 - arm) / 0.05, 0, 1) * np.clip((0.85 - np.abs(x)) / 0.05, 0, 1), "Texture on the stampede route strip (Beam, TextureLength=6, TextureSpeed=2) and the bank chevrons.")

(OUT / "manifest.json").write_text(json.dumps({"_note": "Generated by tools/make_textures.py. White RGB + alpha; tint in engine. Not yet uploaded to Roblox: no asset ids exist.", "textures": manifest}, indent=2) + "\n")
for k, v in manifest.items(): print(f"{k:22} {v['size']} {v['bytes']} bytes")
