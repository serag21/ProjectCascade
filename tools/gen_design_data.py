"""Generate game/ReplicatedStorage/Spark/Design/*.luau from design/fable/data (WP-01).

The JSON under design/fable/data is the single source of gameplay numbers, layouts,
creature models and slice scope. This script mirrors it into plain Luau tables so
game code never retypes a number from a document.

Rules (deterministic: two runs give identical bytes):
  * keys starting with "_" are dropped (notes)
  * a tuning entry {"value": v, ...} collapses to v; its "range" goes to Tuning.Ranges
  * object keys made only of digits become integer keys (e.g. sizeMultiplier[3])
  * object keys are sorted; JSON null values are omitted
  * floats use Python's shortest round-trip repr

Usage:
  python3 tools/gen_design_data.py            # write the modules
  python3 tools/gen_design_data.py --check    # regenerate in memory, fail if any file differs
Stdlib only. Offline.
"""
from pathlib import Path
import json
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "design" / "fable" / "data"
OUT = ROOT / "game" / "ReplicatedStorage" / "Spark" / "Design"
IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
RESERVED = {"and", "break", "do", "else", "elseif", "end", "false", "for", "function", "if", "in", "local",
            "nil", "not", "or", "repeat", "return", "then", "true", "until", "while", "continue", "type", "export"}


def strip(value):
    if isinstance(value, dict):
        return {k: strip(v) for k, v in value.items() if not k.startswith("_") and v is not None}
    if isinstance(value, list):
        return [strip(v) for v in value]
    return value


def lua_string(text):
    out = ['"']
    for ch in text:
        code = ord(ch)
        if ch == "\\": out.append("\\\\")
        elif ch == '"': out.append('\\"')
        elif ch == "\n": out.append("\\n")
        elif ch == "\r": out.append("\\r")
        elif ch == "\t": out.append("\\t")
        elif code < 32: out.append("\\%03d" % code)
        else: out.append(ch)
    out.append('"')
    return "".join(out)


def lua_number(value):
    if isinstance(value, bool):
        raise TypeError("bool is not a number")
    if isinstance(value, int):
        return str(value)
    text = repr(float(value))
    if text in ("inf", "-inf", "nan"):
        raise ValueError("non-finite number in design data")
    return text


def sort_key(key):
    return (0, int(key), "") if key.isdigit() else (1, 0, key)


def lua(value, indent=0):
    pad, inner = "\t" * indent, "\t" * (indent + 1)
    if value is True: return "true"
    if value is False: return "false"
    if isinstance(value, (int, float)): return lua_number(value)
    if isinstance(value, str): return lua_string(value)
    if isinstance(value, list):
        if not value: return "{}"
        items = [lua(v, indent + 1) for v in value]
        flat = "{" + ", ".join(items) + "}"
        if len(flat) <= 100 and "\n" not in flat:
            return flat
        return "{\n" + "".join(inner + item + ",\n" for item in items) + pad + "}"
    if isinstance(value, dict):
        if not value: return "{}"
        lines = []
        for key in sorted(value, key=sort_key):
            if key.isdigit(): name = "[" + key + "]"
            elif IDENT.match(key) and key not in RESERVED: name = key
            else: name = "[" + lua_string(key) + "]"
            lines.append(inner + name + " = " + lua(value[key], indent + 1) + ",\n")
        return "{\n" + "".join(lines) + pad + "}"
    raise TypeError(f"unsupported value {value!r}")


def header(sources, purpose):
    return ("-- GENERATED by tools/gen_design_data.py from " + ", ".join(sources) + ". DO NOT EDIT.\n"
            "-- " + purpose + "\n"
            )


def load(name):
    return json.loads((DATA / name).read_text(encoding="utf-8"))


def tuning_module():
    raw = strip(load("tuning.json"))
    values, ranges = {}, {}
    for section, entries in raw.items():
        if not isinstance(entries, dict):
            values[section] = entries
            continue
        values[section], ranges_section = {}, {}
        for key, entry in entries.items():
            if isinstance(entry, dict) and "value" in entry:
                values[section][key] = entry["value"]
                if "range" in entry:
                    ranges_section[key] = entry["range"]
            else:
                values[section][key] = entry
        if ranges_section:
            ranges[section] = ranges_section
    values["Ranges"] = ranges
    body = "local Tuning = " + lua(values) + "\n\nreturn Tuning\n"
    return header(["tuning.json"], "Gameplay numbers: Tuning.<section>.<key>; tuning ranges in Tuning.Ranges.") + body


def creatures_module():
    raw = strip(load("creatures.json"))
    body = ("local Creatures = " + lua(raw) + "\n\n"
            "Creatures.byId = {}\n"
            "for _, list in ipairs({Creatures.species, Creatures.legends, Creatures.hazards}) do\n"
            "\tfor _, def in ipairs(list) do Creatures.byId[def.id] = def end\n"
            "end\n\nreturn Creatures\n")
    return header(["creatures.json"], "Species, legends and hazards; Creatures.byId[id] indexes all three lists.") + body


def events_module():
    raw = strip(load("events.json"))
    body = ("local Events = " + lua(raw) + "\n\n"
            "Events.byId = {}\n"
            "for _, def in ipairs(Events.events) do Events.byId[def.id] = def end\n\nreturn Events\n")
    return header(["events.json"], "Round beats and arena events on the shared clock; Events.byId[id].") + body


def arenas_module():
    arenas = {p.stem: strip(json.loads(p.read_text(encoding="utf-8"))) for p in sorted((DATA / "arenas").glob("*.json"))}
    order = sorted(arenas, key=lambda k: arenas[k].get("biomeIndex", 99))
    body = ("local Arenas: any = " + lua(arenas) + "\n\n"
            "Arenas.order = " + lua(order) + "\n"
            + ARENA_HELPERS)
    return header(["arenas/" + k + ".json" for k in sorted(arenas)],
                  "Arena layouts (arena-relative studs, +z toward the hub); helpers inBounds, blockers, pinchWalls.") + body


ARENA_HELPERS = """
-- Even-odd point-in-polygon on the bounds ring ([x, z] pairs).
function Arenas.inBounds(arena: any, x: number, z: number): boolean
	local poly = if type(arena) == "string" then Arenas[arena].bounds else arena.bounds
	local inside = false
	local n = #poly
	for i = 1, n do
		local a, b = poly[i], poly[i % n + 1]
		if (a[2] > z) ~= (b[2] > z) and x < (b[1] - a[1]) * (z - a[2]) / (b[2] - a[2]) + a[1] then
			inside = not inside
		end
	end
	return inside
end

-- Features that stop creatures (solid or creatureBlock), in data order.
function Arenas.blockers(arena: any): {any}
	local def = if type(arena) == "string" then Arenas[arena] else arena
	local out = {}
	for _, f in ipairs(def.features) do
		if f.solid or f.creatureBlock then table.insert(out, f) end
	end
	return out
end

-- Features flagged as pinch walls (stage 2 ribbon closure; the boundary hedge also counts).
function Arenas.pinchWalls(arena: any): {any}
	local def = if type(arena) == "string" then Arenas[arena] else arena
	local out = {}
	for _, f in ipairs(def.features) do
		if f.pinch then table.insert(out, f) end
	end
	return out
end

function Arenas.feature(arena: any, id: string): any
	local def = if type(arena) == "string" then Arenas[arena] else arena
	for _, f in ipairs(def.features) do
		if f.id == id then return f end
	end
	return nil
end

return Arenas
"""


def models_module():
    models = {p.stem: strip(json.loads(p.read_text(encoding="utf-8"))) for p in sorted((DATA / "models").glob("*.json"))}
    body = "local Models = " + lua(models) + "\n\nreturn Models\n"
    return header(["models/" + k + ".json" for k in sorted(models)],
                  "Creature part lists and the cinch timeline; Models.meadow_creatures, Models.cinch_effect.") + body


def slice_module():
    raw = strip(load("slice.json"))
    body = ("local Slice: any = " + lua(raw) + "\n" + SLICE_HELPERS)
    return header(["slice.json"], "Checkpoint 1 scope. Code asks Slice.on(id) instead of hard-coding what the slice holds.") + body


SLICE_HELPERS = """
-- on(id): false for anything listed under off or stubbed; true for a slice species,
-- the slice arena, or an exact entry in any 'in' list; false otherwise (fail closed).
local known: {[string]: boolean} = {}
for _, id in ipairs(Slice.species) do known[id] = true end
known[Slice.arena] = true
for _, list in pairs(Slice["in"]) do
	for _, id in ipairs(list) do known[id] = true end
end
function Slice.on(id: string): boolean
	if Slice.off[id] ~= nil or Slice.stubbed[id] ~= nil then return false end
	return known[id] == true
end

function Slice.species_on(id: string): boolean
	return table.find(Slice.species, id) ~= nil
end

return Slice
"""


def ui_module():
    raw = strip(load("ui_layout.json"))
    return header(["ui_layout.json"], "HUD v2 rects at three reference viewports (Hud.luau anchors them).") + \
        "local UiLayout = " + lua(raw) + "\n\nreturn UiLayout\n"


MODULES = {
    "Tuning.luau": tuning_module,
    "Creatures.luau": creatures_module,
    "Events.luau": events_module,
    "Arenas.luau": arenas_module,
    "Models.luau": models_module,
    "Slice.luau": slice_module,
    "UiLayout.luau": ui_module,
}


VECTORS = ROOT / "tests" / "vectors" / "loop_vectors.luau"


def vectors_module():
    raw = strip(load("test_vectors.json"))
    return ("-- GENERATED by tools/gen_design_data.py from design/fable/data/test_vectors.json. DO NOT EDIT.\n"
            "-- Loop reference vectors (closure, containment, validation, resolution, scoring, bank, chain).\n"
            "return " + lua(raw) + "\n")


def render():
    out = {name: build() for name, build in MODULES.items()}
    out[VECTORS] = vectors_module()
    return out


def target(name):
    return name if isinstance(name, Path) else OUT / name


def main(argv):
    rendered = render()
    if "--check" in argv:
        stale = []
        for name, text in rendered.items():
            path = target(name)
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        extra = sorted(p.name for p in OUT.glob("*.luau") if p.name not in rendered) if OUT.exists() else []
        stale = [s if isinstance(s, str) else s.relative_to(ROOT).as_posix() for s in stale]
        if stale or extra:
            print("design-data-fresh: FAIL; regenerate with python3 tools/gen_design_data.py")
            for name in stale: print("  stale: " + name)
            for name in extra: print("  unexpected: " + name)
            return 1
        # Determinism: a second render must be byte-identical.
        if render() != rendered:
            print("design-data-fresh: FAIL; generator is not deterministic")
            return 1
        print(f"design-data-fresh: {len(rendered)} modules match design/fable/data")
        return 0
    for name, text in rendered.items():
        target(name).parent.mkdir(parents=True, exist_ok=True)
        target(name).write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {len(rendered)} files (design modules + loop vectors)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
