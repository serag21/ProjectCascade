"""Generate tests/engine/RobloxApi.luau from a Roblox API dump (data only).

The fake engine in tests/engine/FakeRoblox.luau uses this table to reject
classes, members, read-only writes, security-restricted members and enum items
that real Roblox game scripts could not use. Run whenever the dump is updated:

    python tools/gen_roblox_api.py [--dump .tools/api/Full-API-Dump.json]

Fetch the dump (public, read-only) if missing:
    curl -sSL -o .tools/api/Full-API-Dump.json \
      https://raw.githubusercontent.com/MaximumADHD/Roblox-Client-Tracker/roblox/Full-API-Dump.json
"""
from pathlib import Path
import argparse
import hashlib
import json
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE_URL = "https://raw.githubusercontent.com/MaximumADHD/Roblox-Client-Tracker/roblox/Full-API-Dump.json"
CATEGORY = {"Primitive": "P", "DataType": "D", "Enum": "E", "Class": "C", "Group": "G"}


def accessible(security, key):
    """Game scripts run at the lowest identity: only 'None' security is usable."""
    if isinstance(security, str):
        return security == "None"
    return security.get(key, "None") == "None"


def lua_string(value: str) -> str:
    return json.dumps(value)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--dump", type=Path, default=ROOT / ".tools" / "api" / "Full-API-Dump.json")
    parser.add_argument("--out", type=Path, default=ROOT / "tests" / "engine" / "RobloxApi.luau")
    args = parser.parse_args()
    if not args.dump.exists():
        print(f"Missing {args.dump}. Fetch it with:\n  curl -sSL -o {args.dump} {SOURCE_URL}")
        return 2
    raw = args.dump.read_bytes()
    dump = json.loads(raw)
    lines = [
        "-- GENERATED by tools/gen_roblox_api.py. Do not edit by hand.",
        f"-- Source: {SOURCE_URL}",
        f"-- Dump format version {dump.get('Version')}; sha256 {hashlib.sha256(raw).hexdigest()}",
        "-- Property code: <flags><category><type>. Flags: ! not writable by game scripts",
        "-- (ReadOnly tag or write security), ? not readable by game scripts. Categories:",
        "-- P primitive, D datatype, E enum, C class, G group, F callback.",
        "return {classes={",
    ]
    for cls in sorted(dump["Classes"], key=lambda c: c["Name"]):
        tags = [t for t in (cls.get("Tags") or []) if isinstance(t, str)]
        props, funcs, events = [], [], []
        for member in cls["Members"]:
            kind, name = member["MemberType"], member["Name"]
            security = member.get("Security", "None")
            mtags = [t for t in (member.get("Tags") or []) if isinstance(t, str)]
            if kind == "Property":
                flags = ""
                if "ReadOnly" in mtags or not accessible(security, "Write"):
                    flags += "!"
                if not accessible(security, "Read"):
                    flags += "?"
                value = member.get("ValueType", {})
                code = flags + CATEGORY.get(value.get("Category"), "P") + value.get("Name", "any")
                props.append(f"[{lua_string(name)}]={lua_string(code)}")
            elif kind == "Callback":
                if accessible(security, "Write"):
                    props.append(f"[{lua_string(name)}]=\"Ffunction\"")
            elif kind == "Function":
                if accessible(security, "Read") if isinstance(security, dict) else security == "None":
                    funcs.append(name)
            elif kind == "Event":
                if accessible(security, "Read") if isinstance(security, dict) else security == "None":
                    events.append(name)
        flags = ("N" if "NotCreatable" in tags else "") + ("S" if "Service" in tags else "")
        lines.append(
            f"[{lua_string(cls['Name'])}]={{s={lua_string(cls.get('Superclass') or '')},t={lua_string(flags)},"
            f"p={{{','.join(props)}}},f={lua_string(' '.join(funcs))},e={lua_string(' '.join(events))}}},"
        )
    lines.append("},enums={")
    for enum in sorted(dump["Enums"], key=lambda e: e["Name"]):
        items = " ".join(f"{item['Name']}:{item['Value']}" for item in enum["Items"])
        lines.append(f"[{lua_string(enum['Name'])}]={lua_string(items)},")
    lines.append("}}")
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(json.dumps({"classes": len(dump["Classes"]), "enums": len(dump["Enums"]), "out": str(args.out),
                      "bytes": args.out.stat().st_size}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
